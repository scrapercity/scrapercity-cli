// scripts/python-catalog.mjs - writes the Python SDK's tool list (python/scrapercity/_catalog.py)
// from the same tools the MCP server serves: the hand-written ones (lib/utilityTools.mjs) plus the
// generated scraper tools. Called by scripts/generate.mjs on every generate and publish, so the
// Python SDK can never fall behind the MCP. The Python version follows package.json.
import fs from 'fs'
import path from 'path'

export function writePythonCatalog({ root, utilityTools, scraperTools, endpointByTool, endpoints, version, fail }) {
  const tools = [...utilityTools, ...scraperTools]

  // Every hand-written tool needs a handler in python/scrapercity/tools.py.
  const toolsPy = fs.readFileSync(path.join(root, 'python', 'scrapercity', 'tools.py'), 'utf-8')
  const missing = utilityTools.map(t => t.name).filter(n => !toolsPy.includes(`"${n}":`))
  if (missing.length) fail(`python/scrapercity/tools.py has no handler for: ${missing.join(', ')}. Add one to _UTILITY_HANDLERS.`)
  if (!/^\d+\.\d+\.\d+$/.test(version)) fail(`package.json version "${version}" is not x.y.z`)

  // A JSON string literal is also a valid Python string literal, so json.loads reads it back exactly.
  const lit = (v) => JSON.stringify(JSON.stringify(v))
  const out =
    '# AUTO-GENERATED by scripts/generate.mjs - DO NOT EDIT BY HAND.\n' +
    '# The same tool list the ScraperCity MCP server serves (lib/utilityTools.mjs + the tools generated\n' +
    '# from scraperConfigs.ts). Regenerate: npm run generate\n' +
    'import json\n\n' +
    `VERSION = ${JSON.stringify(version)}\n\n` +
    `TOOLS = json.loads(${lit(tools)})\n\n` +
    `ENDPOINT_BY_TOOL = json.loads(${lit(endpointByTool)})\n\n` +
    `ENDPOINTS = json.loads(${lit(endpoints)})\n`
  const outPath = path.join(root, 'python', 'scrapercity', '_catalog.py')
  const prev = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf-8') : ''
  fs.writeFileSync(outPath, out)
  return { changed: prev !== out, count: tools.length }
}
